#!/usr/bin/env node
/**
 * Stage 09: human-readable lineage for a deterministic, stratified sample of
 * 100+ records -> docs/data_recovery/LINEAGE_SAMPLE.md
 * Sampling is seeded (RECOVERY_SAMPLE_SEED, default 20260927) so re-runs match.
 */
import path from "node:path";
import { CANONICAL_DIR, DOCS_DIR, streamJsonl, writeText } from "./lib/common.mjs";
import { collectLineage, renderLineage } from "./lib/lineage.mjs";

function rng(seed) {
    let s = seed >>> 0;
    return () => { s = (s + 0x6d2b79f5) >>> 0; let t = s; t = Math.imul(t ^ (t >>> 15), t | 1); t ^= t + Math.imul(t ^ (t >>> 7), t | 61); return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };
}

export async function runLineage() {
    const rand = rng(Number(process.env.RECOVERY_SAMPLE_SEED || 20260927));
    const strata = new Map();
    for (const file of ["qbg_questions.jsonl", "source_document_questions.jsonl"]) {
        for await (const r of streamJsonl(path.join(CANONICAL_DIR, file))) {
            const s = `${r.origin_type}|${r.recovery_class}`;
            if (!strata.has(s)) strata.set(s, []);
            strata.get(s).push(r.record_key);
        }
    }
    const available = new Map([...strata].map(([k, l]) => [k, l.length]));
    // quota per stratum: at least 3 where available, rest proportional, total >= 100
    const total = [...strata.values()].reduce((n, l) => n + l.length, 0);
    const picks = [];
    for (const [s, list] of [...strata].sort()) {
        const quota = Math.min(list.length, Math.max(3, Math.round((list.length / total) * 80)));
        const pool = [...list];
        for (let i = 0; i < quota; i++) picks.push({ s, key: pool.splice(Math.floor(rand() * pool.length), 1)[0] });
        strata.set(s, pool); // remaining pool for top-up
    }
    const TARGET = 100;
    const bySize = [...strata].sort((a, b) => b[1].length - a[1].length);
    for (let i = 0; picks.length < TARGET && i < 1000; i++) {
        const [s, pool] = bySize[i % bySize.length];
        if (pool.length) picks.push({ s, key: pool.splice(Math.floor(rand() * pool.length), 1)[0] });
    }
    picks.sort((a, b) => (a.s < b.s ? -1 : a.s > b.s ? 1 : 0));
    const lin = await collectLineage(picks.map((p) => p.key));
    const body = picks.map((p, i) => `### ${i + 1}. ${p.key}  \`[${p.s}]\`\n\n\`\`\`text\n${renderLineage(lin.get(p.key))}\n\`\`\``);
    writeText(path.join(DOCS_DIR, "LINEAGE_SAMPLE.md"), [
        "# Lineage sample",
        "",
        `Deterministic stratified sample of **${picks.length}** records (seed ${process.env.RECOVERY_SAMPLE_SEED || 20260927}), generated by \`node scripts/data/recovery/09_lineage.mjs\`.`,
        "Any single record can be traced the same way with `node scripts/data/recovery/query.mjs <qbg_id|record_key|question_id>`.",
        "",
        "Strata (origin | class : sampled / available):",
        "",
        ...[...available].sort().map(([s, n]) => `- ${s}: ${picks.filter((p) => p.s === s).length} / ${n}`),
        "",
        ...body,
    ].join("\n"));
    return picks.length;
}

if (process.argv[1]?.endsWith("09_lineage.mjs")) console.log(`lineage sample: ${await runLineage()} records`);
